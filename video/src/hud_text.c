static int hud_text_index(char character)
{
    if (character >= '0' && character <= '9') return character - '0';
    if (character >= 'A' && character <= 'Z') return 10 + character - 'A';
    switch (character) {
    case '.': return 36;
    case ':': return 37;
    case '-': return 38;
    case '+': return 39;
    case '%': return 40;
    case '/': return 41;
    default: return 42;
    }
}

static uint8_t hud_text_coverage(double distance)
{
    if (distance >= 0.65) return 255U;
    if (distance <= -0.35) return 0U;
    return (uint8_t)lround((distance + 0.35) * 255.0);
}

int hud_text_atlas_init(HudTextAtlas *atlas)
{
    uint32_t glyph;
    uint32_t y;
    const uint32_t width = HUD_TEXT_BASE_WIDTH * HUD_TEXT_SUPERSAMPLE;
    const uint32_t height = HUD_TEXT_BASE_HEIGHT * HUD_TEXT_SUPERSAMPLE;

    if (atlas == NULL) {
        errno = EINVAL;
        return -1;
    }
    memset(atlas, 0, sizeof(*atlas));
    atlas->stride = width;
    atlas->glyph_width = width;
    atlas->glyph_height = height;
    atlas->advance = 6U * HUD_TEXT_SUPERSAMPLE;
    atlas->glyph_count = HUD_TEXT_GLYPH_COUNT;
    atlas->bytes = (size_t)atlas->glyph_count * height * width;
    atlas->coverage = calloc(1U, atlas->bytes);
    if (atlas->coverage == NULL) {
        return -1;
    }
    for (glyph = 0U; glyph < atlas->glyph_count; ++glyph) {
        for (y = 0U; y < height; ++y) {
            uint32_t x;
            for (x = 0U; x < width; ++x) {
                uint32_t cell_x = x / HUD_TEXT_SUPERSAMPLE;
                uint32_t cell_y = y / HUD_TEXT_SUPERSAMPLE;
                double center_x = (double)(x % HUD_TEXT_SUPERSAMPLE) + 0.5;
                double center_y = (double)(y % HUD_TEXT_SUPERSAMPLE) + 0.5;
                const uint8_t mask = hud_text_masks[glyph][cell_y];
                bool active = (mask & (1U << (4U - cell_x))) != 0U;
                double distance;

                if (!active) {
                    continue;
                }
                /* A narrow rounded stroke gives the fixed-width atlas
                 * fractional edge coverage without a runtime font engine. */
                distance = fmin(fmin(center_x - 0.35,
                                     (double)HUD_TEXT_SUPERSAMPLE - 0.35 -
                                         center_x),
                                fmin(center_y - 0.35,
                                     (double)HUD_TEXT_SUPERSAMPLE - 0.35 -
                                         center_y));
                atlas->coverage[(size_t)glyph * height * width +
                                (size_t)y * width + x] =
                    hud_text_coverage(distance);
            }
        }
    }
    atlas->initialized = true;
    return 0;
}

void hud_text_atlas_close(HudTextAtlas *atlas)
{
    if (atlas == NULL) return;
    free(atlas->coverage);
    memset(atlas, 0, sizeof(*atlas));
}

uint32_t hud_text_width(const HudTextAtlas *atlas, const char *text,
                        uint32_t pixel_size)
{
    size_t length;

    if (atlas == NULL || !atlas->initialized || text == NULL ||
        pixel_size == 0U) return 0U;
    length = strlen(text);
    if (length > UINT32_MAX / (6U * pixel_size)) return UINT32_MAX;
    return (uint32_t)length * 6U * pixel_size;
}

bool hud_text_draw(const HudTextAtlas *atlas, HudLayer *layer, int x, int y,
                   const char *text, uint32_t pixel_size, HudTextColor color)
{
    uint32_t glyph_width;
    uint32_t glyph_height;
    uint32_t character_index;

    if (atlas == NULL || !atlas->initialized || layer == NULL ||
        layer->pixels == NULL || text == NULL || pixel_size == 0U) return false;
    glyph_width = HUD_TEXT_BASE_WIDTH * pixel_size;
    glyph_height = HUD_TEXT_BASE_HEIGHT * pixel_size;
    for (character_index = 0U; text[character_index] != '\0';
         ++character_index) {
        int index = hud_text_index(text[character_index]);
        uint32_t output_y;

        if (index != 42) {
            if (pixel_size == HUD_TEXT_SUPERSAMPLE) {
                const uint8_t *glyph = atlas->coverage +
                    (size_t)index * atlas->glyph_height * atlas->glyph_width;

                (void)hud_blend_coverage(
                    layer, x + (int)character_index * (int)atlas->advance,
                    y, atlas->glyph_width, atlas->glyph_height, glyph,
                    atlas->stride, color.red, color.green, color.blue,
                    color.alpha);
                continue;
            }
            for (output_y = 0U; output_y < glyph_height; ++output_y) {
                uint32_t output_x;
                uint32_t source_y = (uint32_t)(((uint64_t)output_y *
                    atlas->glyph_height) / glyph_height);
                for (output_x = 0U; output_x < glyph_width; ++output_x) {
                    uint32_t source_x = (uint32_t)(((uint64_t)output_x *
                        atlas->glyph_width) / glyph_width);
                    uint8_t coverage = atlas->coverage[
                        (size_t)index * atlas->glyph_height * atlas->glyph_width +
                        (size_t)source_y * atlas->glyph_width + source_x];
                    uint8_t alpha = (uint8_t)(((unsigned int)color.alpha *
                                               coverage + 127U) / 255U);
                    if (alpha != 0U) {
                        hud_blend_pixel(layer, x + (int)character_index *
                                        (int)(6U * pixel_size) + (int)output_x,
                                        y + (int)output_y, color.red,
                                        color.green, color.blue, alpha);
                    }
                }
            }
        }
    }
    return true;
}
